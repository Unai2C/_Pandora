// Brings a fresh scripts/export_scene.py export in line with the pandora-v0-20261031 models:
// - The Blender exporter embeds every texture in each GLB. The world models share two small textures, so the embedded
//   copies are replaced by a reference to the shared file (textures/<name>.png next to the models) and their bytes
//   dropped. Water keeps its embedded texture, as in v0.
// - Blender 5.2 no longer writes the emission texture of the gradient-textured vegetation (the base colour wired into
//   emission by the exporter); a textured material with emission gets its base colour texture as emission again.
// Run from the project root after the export: node scripts/finish-export.cjs pandora-v1-20261103
const fs=require('fs'),path=require('path')
const folder=process.argv[2];if(!folder)throw new Error('usage: node scripts/finish-export.cjs <model folder>')
const DIR=path.join('assets/scene/modelos',folder),SHARED=path.join('assets/scene/modelos/pandora-v0-20261031/textures')
const FILES={PP_Color_Palette:'PP_Color_Palette.png',texture_gradient:'texture_gradient.png'}
fs.mkdirSync(path.join(DIR,'textures'),{recursive:true})
// Byte-identical copies of the shared files, so the deployed content is the same file as v0's.
for(const file of Object.values(FILES))fs.copyFileSync(path.join(SHARED,file),path.join(DIR,'textures',file))
let changed=0,saved=0
for(const name of fs.readdirSync(DIR).filter(f=>f.endsWith('.glb'))){
 const file=path.join(DIR,name),b=fs.readFileSync(file),len=b.readUInt32LE(12),j=JSON.parse(b.subarray(20,20+len)),bin=b.subarray(28+len,28+len+b.readUInt32LE(20+len))
 const drop=new Set()
 for(const image of j.images||[]){
  const target=FILES[(image.name||'').replace(/\.png$/,'').replace(/\.\d+$/,'')]
  if(target&&image.bufferView!==undefined){drop.add(image.bufferView);delete image.bufferView;delete image.mimeType;image.uri='textures/'+target}
 }
 let emission=false
 for(const m of j.materials||[]){const base=m.pbrMetallicRoughness?.baseColorTexture;if(base&&!m.emissiveTexture&&(m.emissiveFactor||[]).some(v=>v>0)){m.emissiveTexture={index:base.index};emission=true}}
 if(!drop.size&&!emission)continue
 // Repack the remaining views in order, 4-byte aligned, and renumber references to them.
 const chunks=[],remap=new Map();let offset=0
 j.bufferViews.forEach((v,i)=>{if(drop.has(i))return;const data=bin.subarray(v.byteOffset||0,(v.byteOffset||0)+v.byteLength),pad=(4-offset%4)%4
  if(pad){chunks.push(Buffer.alloc(pad));offset+=pad};remap.set(i,remap.size);chunks.push(data);v.byteOffset=offset;offset+=data.length})
 j.bufferViews=j.bufferViews.filter((_,i)=>!drop.has(i))
 // Morph targets are sparse accessors, whose indices and values sit in views of their own.
 for(const a of j.accessors||[]){if(a.bufferView!==undefined)a.bufferView=remap.get(a.bufferView);if(a.sparse){a.sparse.indices.bufferView=remap.get(a.sparse.indices.bufferView);a.sparse.values.bufferView=remap.get(a.sparse.values.bufferView)}}
 for(const image of j.images||[])if(image.bufferView!==undefined)image.bufferView=remap.get(image.bufferView)
 let out=Buffer.concat(chunks);out=Buffer.concat([out,Buffer.alloc((4-out.length%4)%4)]);j.buffers=[{byteLength:out.length}]
 let json=Buffer.from(JSON.stringify(j));json=Buffer.concat([json,Buffer.alloc((4-json.length%4)%4,0x20)])
 const head=Buffer.alloc(20);head.writeUInt32LE(0x46546C67,0);head.writeUInt32LE(2,4);head.writeUInt32LE(20+json.length+8+out.length,8);head.writeUInt32LE(json.length,12);head.writeUInt32LE(0x4E4F534A,16)
 const binHead=Buffer.alloc(8);binHead.writeUInt32LE(out.length,0);binHead.writeUInt32LE(0x004E4942,4)
 const result=Buffer.concat([head,json,binHead,out]);saved+=b.length-result.length;changed++
 fs.writeFileSync(file,result)
}
console.log(changed+' models updated (shared textures, emission), '+(saved/1e6).toFixed(1)+' MB smaller')
// The tutorial highlight lights a resource up in its own colours, which needs the shared texture its ON model uses.
const manifestFile=path.join(DIR,'manifest.json')
if(fs.existsSync(manifestFile)){
 const manifest=JSON.parse(fs.readFileSync(manifestFile,'utf8')),textures=[],byId={}
 for(const r of manifest.resources){const b=fs.readFileSync(r.on),j=JSON.parse(b.subarray(20,20+b.readUInt32LE(12))),uri=(j.images||[]).find(i=>i.uri)?.uri
  if(!uri)continue;const src=path.posix.join(path.posix.dirname(r.on),uri);if(!textures.includes(src))textures.push(src);byId[r.id]=textures.indexOf(src)}
 fs.writeFileSync('src/shared/resourceTextures.ts','// Generated by scripts/finish-export.cjs: the shared texture each resource\'s ON model uses.\nconst TEXTURES='+JSON.stringify(textures)+'\nconst BY_ID:Record<string,number>='+JSON.stringify(byId)+'\nexport function resourceTexture(id:string){const index=BY_ID[id];return index===undefined?undefined:TEXTURES[index]}\n')
 console.log('resource textures for '+Object.keys(byId).length+' resources')
}
