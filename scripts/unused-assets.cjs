// Lists the files under assets/ that the scene never loads and checks that .dclignore leaves them out (and nothing
// used), so the Explorer neither converts nor downloads them (nothing is deleted). "Used" means: a path written in the built bin/index.js, a path the
// code builds at runtime (patterns below), a file scene.json names, or a texture a used GLB points to.
// Run from the project root after `npm run build`: node scripts/unused-assets.cjs [--list]. It checks .dclignore, which is
// kept by hand as a short list of folders and wildcards (a long list makes the preview server time out).
const fs=require('fs'),path=require('path')
const bundle=fs.readFileSync('bin/index.js','utf8'),scene=fs.readFileSync('scene.json','utf8')
const walk=d=>fs.readdirSync(d,{withFileTypes:true}).flatMap(e=>e.isDirectory()?walk(path.posix.join(d,e.name)):[path.posix.join(d,e.name)])
const files=walk('assets')
// Paths the code assembles from parts (see the template strings in src).
// Agents load by their configured name (agents.ts AGENT_CONFIG) or id.
const ids=[...new Set([...bundle.matchAll(/(?:id|name):\s*"([A-Za-z_]+)"/g)].map(m=>m[1]))]
const dynamic=[
 /^assets\/images\/story\/lore-dcl-v3\/memory-0[1-8]\.png$/,
 /^assets\/images\/ui-rpg\/(sword|axe|pickaxe)-icon\.png$/,
 /^assets\/scene\/modelos\/arbol-central\/fade\/Tree_0[1-4]_base\.jpg$/,
 new RegExp('^assets/images/agents/('+ids.join('|')+')\\.png$'),
 new RegExp('^assets/scene/modelos/Agentes/('+ids.join('|')+')_anim\\.glb$'),
 // fx models created by name (the minified bundle renames the helper, so any quoted name counts), plus agent rings.
 new RegExp('^assets/scene/modelos/fx/('+fs.readdirSync('assets/scene/modelos/fx').map(f=>f.replace(/.glb$/,'')).filter(n=>bundle.includes('"'+n+'"')).concat(['Agent_Rings_Friendly','Agent_Rings_Corrupt','LevelUp_Rings']).join('|')+')\.glb$'),
 // emotes are named without their folder; tools by name.
 new RegExp('^assets/scene/modelos/animaciones/('+[...bundle.matchAll(/"([A-Za-z_]+_emote\.glb)"/g)].map(m=>m[1].replace('.','\\.')).join('|')+')$'),
 new RegExp('^assets/scene/modelos/(Axe|Pickaxe|Sword)\\.glb$')
]
const lower=scene.toLowerCase()
// Creator Hub files stay: the editor composite and the generated thumbnail.
const keep=['assets/scene/main.composite','assets/images/autogenerated-thumbnail.png']
const used=new Set(files.filter(f=>keep.includes(f)||bundle.includes(f)||lower.includes(f.toLowerCase())||dynamic.some(r=>r.test(f))))
// External textures of used GLBs.
for(const f of [...used].filter(f=>f.endsWith('.glb'))){const b=fs.readFileSync(f),j=JSON.parse(b.subarray(20,20+b.readUInt32LE(12)));for(const image of j.images||[])if(image.uri)used.add(path.posix.normalize(path.posix.join(path.posix.dirname(f),decodeURI(image.uri))))}
const unused=files.filter(f=>!used.has(f))
// Collapse folders that are entirely unused.
const dirs=new Map();for(const f of files){let d=path.posix.dirname(f);while(d!=='.'&&d!=='assets'){if(!dirs.has(d))dirs.set(d,{all:0,unused:0});const s=dirs.get(d);s.all++;if(!used.has(f))s.unused++;d=path.posix.dirname(d)}}
const whole=[...dirs].filter(([d,s])=>s.all===s.unused&&!dirs.has(path.posix.dirname(d))||s.all===s.unused&&dirs.get(path.posix.dirname(d)).all!==dirs.get(path.posix.dirname(d)).unused).map(([d])=>d).sort()
const lines=[...whole,...unused.filter(f=>!whole.some(d=>f.startsWith(d+'/')))].map(p=>p.replace(/([\[\]!#*?])/g,'\\$1'))
const mb=fs=>(fs.reduce((s,f)=>s+require('fs').statSync(f).size,0)/1e6).toFixed(1)
console.log('assets',files.length,'used',used.size,mb([...used].filter(f=>files.includes(f))),'MB · unused',unused.length,mb(unused),'MB')
if(process.argv.includes('--list'))console.log(lines.join('\n'))
// Check the hand-kept .dclignore (short on purpose) against what is used.
const ignore=require('ignore'),ig=(ignore.default||ignore)().add(fs.readFileSync('.dclignore','utf8').split('\n').filter(Boolean))
const wronglyIgnored=[...used].filter(f=>files.includes(f)&&ig.ignores(f)),stillShipped=unused.filter(f=>!ig.ignores(f))
console.log('.dclignore: used but ignored',wronglyIgnored.length,'· unused but still shipped',stillShipped.length)
for(const f of wronglyIgnored)console.log('  USED, IGNORED:',f)
for(const f of stillShipped)console.log('  unused, shipped:',f)
if(wronglyIgnored.length)process.exitCode=1
