// Writes two lookup tables the scene uses at runtime, measured from the exported models:
// - src/shared/terrainGrid.ts: ground height and ground kind every 2 m over the 160 x 160 m scene (0 open ground,
//   1 rock or mountain, 2 lake, 3 nothing; the tree platform counts as open ground), for camera framing and respawn.
// - src/shared/treeReach.ts: for each central tree stage, how far its collider reaches from the trunk root near the
//   ground in 16 directions (model units, before the growth scale), so a respawn point never lands inside it.
// Run from the project root after an export: node scripts/world-grids.cjs
const fs=require('fs'),path=require('path')
const {root,glb,data,base}=require('./world-terrain.cjs')
const STEP=2,SIZE=160,N=SIZE/STEP+1
const heights=[],kinds=[]
for(let k=0;k<N;k++)for(let i=0;i<N;i++){const h=base.height(i*STEP,k*STEP)
 heights.push(h?Math.round(h.y*10):0);kinds.push(!h?3:/Lake/i.test(h.name)?2:/^PP_PLANE|Stone_Path|Plateau/.test(h.name)?0:1)}
fs.writeFileSync(path.join(root,'src/shared/terrainGrid.ts'),`// Generated by scripts/world-grids.cjs from the exported base: ground every ${STEP} m, heights in decimetres.
const STEP=${STEP},N=${N}
const HEIGHTS=${JSON.stringify(heights)}
const KINDS='${kinds.join('')}'
const at=(x:number,z:number)=>{const i=Math.max(0,Math.min(N-1,Math.round(x/STEP))),k=Math.max(0,Math.min(N-1,Math.round(z/STEP)));return k*N+i}
export function groundHeight(x:number,z:number){return HEIGHTS[at(x,z)]/10}
// 0 open ground, 1 rock or mountain, 2 lake, 3 nothing.
export function groundKind(x:number,z:number){return +KINDS[at(x,z)]}
`)
const ROOTS=[[-.70620197057724,1.6245012283325195,-.13632047176361084],[-.03294026106595993,1.7156212329864502,-1.4084560871124268],[-1.4991445541381836,2.0154078006744385,.9307258129119873],[-1.4254231452941895,1.6461341381072998,.41213348507881165]]
const reach=[]
for(let s=0;s<4;s++){
 const g=glb(`assets/scene/modelos/arbol-central/Tree_0${s+1}_anim.glb`),n=g.j.nodes.find(n=>n.name==='Tree_collider'),p=g.j.meshes[n.mesh].primitives[0],P=data(g,p.attributes.POSITION),I=data(g,p.indices),r=ROOTS[s]
 const dirs=new Array(16).fill(0)
 // Sample each triangle densely; anything up to 3 m above the root counts as blocking a standing avatar.
 for(let i=0;i<I.length;i+=3){const t=[P[I[i]],P[I[i+1]],P[I[i+2]]];for(let a=0;a<=6;a++)for(let b=0;b<=6-a;b++){const c=6-a-b,q=[0,1,2].map(d=>(t[0][d]*a+t[1][d]*b+t[2][d]*c)/6)
  if(q[1]<r[1]-.3||q[1]>r[1]+3)continue
  const dx=q[0]-r[0],dz=q[2]-r[2],d=Math.round(((Math.atan2(dz,dx)+2*Math.PI)%(2*Math.PI))/(2*Math.PI)*16)%16
  for(const k of [d,(d+1)%16,(d+15)%16])dirs[k]=Math.max(dirs[k],Math.hypot(dx,dz))}}
 reach.push(dirs.map(v=>+v.toFixed(2)))
}
fs.writeFileSync(path.join(root,'src/shared/treeReach.ts'),`// Generated by scripts/world-grids.cjs: how far each central tree stage's collider reaches from its trunk root near the
// ground, in 16 directions (index k points at angle k*22.5 degrees from +x towards +z), in model units.
export const TREE_REACH=${JSON.stringify(reach)}
`)
console.log('terrain grid',N+'x'+N,'tree reach',reach.map(r=>Math.max(...r).toFixed(1)+'/'+Math.min(...r).toFixed(1)).join(' '))
